/** One labelled sample: features at time t, and what happened next. */
class LinkSample(val features: DoubleArray, val lossNextWindow: Int, val lost5s: Int, val route: Int)

/**
 * Turns tracker features into labelled rows once the future is known. The same code labels real
 * phone logs (exported from the app) and simulated routes.
 */
class LinkLabeler(private val tracker: LinkTracker, private val slotMs: Long = LinkTracker.SLOT_MS) {
    private class Pending(val id: Int, val t: Long, val features: DoubleArray)
    private val pending = ArrayDeque<Pending>()

    fun sample(id: Int, t: Long, features: DoubleArray) { pending.addLast(Pending(id, t, features)) }

    /**
     * Labels samples at least 5 s old. loss_next_window = fewer than 2 frames in the next 600 ms
     * (2 expected at one frame per 250 ms, with slack for timing jitter); lost_5s = no frame in 5 s.
     */
    fun finalize(now: Long, emit: (id: Int, t: Long, features: DoubleArray, loss: Int, lost5s: Int) -> Unit) {
        while (pending.isNotEmpty() && now - pending.first().t >= 5_000) {
            val s = pending.removeFirst()
            val frames = tracker.neighbors[s.id]?.frames.orEmpty()
            val next600 = frames.count { it.timeMs > s.t && it.timeMs <= s.t + 600 }
            val next5 = frames.count { it.timeMs > s.t && it.timeMs <= s.t + 5_000 }
            emit(s.id, s.t, s.features, if (next600 < 2) 1 else 0, if (next5 == 0) 1 else 0)
        }
    }
}

object LinkDataset {
    /**
     * One route: a phone moves relative to a listener for [durationS] seconds (walking, stopping, turning
     * back), in a randomly drawn radio environment, on 1M or Coded PHY.
     */
    fun route(routeId: Int, seed: Long, durationS: Int = 120): List<LinkSample> {
        val r = Random(seed)
        val env = RadioEnv.random(r)
        val coded = r.nextBoolean()
        val link = LinkState(env, r)
        val tracker = LinkTracker()
        val labeler = LinkLabeler(tracker)
        val out = ArrayList<LinkSample>()
        var d = r.nextDouble(2.0, if (coded) 160.0 else 80.0)
        var v = r.nextDouble(-1.4, 1.4)
        val slot = LinkTracker.SLOT_MS
        var t = 1_000_000L
        var seq = 0
        val end = t + durationS * 1000L
        while (t <= end + 6_000) {
            if (r.nextDouble() < 0.01) v = if (r.nextDouble() < 0.3) 0.0 else r.nextDouble(-1.4, 1.4)
            d = (d + v * slot / 1000.0).coerceIn(1.0, 250.0)
            if (d <= 1.0 || d >= 250.0) v = -v
            seq = (seq + 1) and 0xFFFF
            val (ok, rssi) = link.slot(d, coded, slot / 1000.0)
            if (ok) tracker.onFrame(7, seq, rssi, coded, t)
            if (t <= end && t % 1000 == 0L) labeler.sample(7, t, tracker.features(7, t, queueDepth = r.nextInt(0, 6), codedMode = coded, distanceM = d))
            labeler.finalize(t) { _, _, f, loss, lost -> out += LinkSample(f, loss, lost, routeId) }
            t += slot
        }
        return out
    }

    fun build(routes: Int, seed: Long) = (0 until routes).flatMap { route(it, seed * 7919 + it) }
}

/** Entry point for `./gradlew :core:trainLinkModel`: trains the ablation set, writes the model and a report. */
fun main(args: Array<String>) {
    val modelOut = File(args.getOrElse(0) { "loss_predictor_v1.txt" })
    val reportOut = File(args.getOrElse(1) { "LINK_PREDICTOR_RESULTS.md" })
    val seed = 20261011L
    val routes = 400
    val data = LinkDataset.build(routes, seed)
    // Hold out whole routes (not random rows), so near-identical neighbouring samples never leak into the test set.
    val testRoutes = (0 until routes).shuffled(Random(seed)).take(routes * 3 / 10).toSet()
    val train = data.filter { it.route !in testRoutes }
    val test = data.filter { it.route in testRoutes }

    val report = StringBuilder()
    report.appendLine("# Link loss predictor: measured results")
    report.appendLine()
    report.appendLine("Generated by `./gradlew :core:trainLinkModel` on ${LocalDate.now()}. Rerun instead of editing.")
    report.appendLine()
    report.appendLine("**Data:** simulated phone-to-phone BLE advertising links (`RadioModel.kt`), $routes routes of 120 s, one sample per second.")
    report.appendLine("The radio model's parameters are assumptions, so these numbers compare feature sets with each other;")
    report.appendLine("they do not predict accuracy on real phones. The app logs the same features on real phones for retraining.")
    report.appendLine()
    report.appendLine("**Split:** ${routes - testRoutes.size} training routes, ${testRoutes.size} held-out test routes (${train.size} / ${test.size} samples).")
    report.appendLine()
    var deployed: LossPredictor? = null
    for ((label, pick) in listOf<Pair<String, (LinkSample) -> Int>>(
        "loss in the next 0.6 s window" to { it.lossNextWindow },
        "neighbour lost for the next 5 s" to { it.lost5s },
    )) {
        val ytr = train.map(pick); val yte = test.map(pick)
        report.appendLine("## Target: $label")
        report.appendLine()
        report.appendLine("Base rate in test set: ${"%.1f".format(yte.average() * 100)}% (a model predicting the base rate has PR-AUC equal to it).")
        report.appendLine()
        report.appendLine("| Features | PR-AUC | Brier score | Recall at 10% false alarms |")
        report.appendLine("|---|---|---|---|")
        var calibration: List<Triple<Double, Double, Int>> = emptyList()
        for ((name, cols) in LinkFeatures.SETS) {
            val m = LossPredictor.train(train.map { it.features }, ytr, cols)
            val p = test.map { m.predict(it.features) }
            report.appendLine("| $name | ${"%.3f".format(Metrics.prAuc(p, yte))} | ${"%.4f".format(Metrics.brier(p, yte))} | ${"%.1f".format(Metrics.recallAtFpr(p, yte, 0.10) * 100)}% |")
            if (label.startsWith("loss") && name == LinkFeatures.DEPLOYED) {
                deployed = m.withMeta(linkedMapOf(
                    "trained_at" to LocalDate.now().toString(), "target" to "loss_next_0_6s", "samples" to train.size.toString(),
                    "routes" to (routes - testRoutes.size).toString(), "data" to "simulated_ble_links_not_real_measurements",
                ))
                calibration = Metrics.calibration(p, yte)
            }
        }
        if (calibration.isNotEmpty()) {
            report.appendLine()
            report.appendLine("Calibration of the deployed model on the test routes:")
            report.appendLine()
            report.appendLine("| Mean predicted | Observed | Samples |")
            report.appendLine("|---|---|---|")
            for ((mp, obs, n) in calibration) report.appendLine("| ${"%.2f".format(mp)} | ${"%.2f".format(obs)} | $n |")
            val worst = calibration.filter { it.third >= 50 }.maxOfOrNull { abs(it.first - it.second) } ?: 0.0
            report.appendLine()
            report.appendLine("Largest calibration gap in bins with 50+ samples: ${"%.2f".format(worst)}.")
        }
        report.appendLine()
    }
    report.appendLine("The deployed model is the full feature set on the 0.6 s loss target. It does not use distance, which phones cannot measure.")
    modelOut.parentFile?.mkdirs()
    modelOut.writeText(deployed!!.write())
    reportOut.parentFile?.mkdirs()
    reportOut.writeText(report.toString())
    println("wrote ${modelOut.absolutePath} and ${reportOut.absolutePath}")
}

