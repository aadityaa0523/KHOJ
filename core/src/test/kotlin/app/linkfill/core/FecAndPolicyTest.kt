class FecAndPolicyTest {
    @Test fun gfInverse() {
        for (a in 1..255) assertEquals(1, GF256.mul(a, GF256.inv(a)))
    }

    @Test fun reedSolomonRebuildsFromAnyKShards() {
        val r = Random(3)
        repeat(200) {
            val k = r.nextInt(1, 12); val m = r.nextInt(0, 6)
            val payload = ByteArray(r.nextInt(1, 2000)).also(r::nextBytes)
            val shards = FecCodec.split(payload, k, m)
            val keep = shards.indices.shuffled(r).take(k).associateWith { shards[it] }
            assertArrayEquals(payload, FecCodec.join(keep, k, m, payload.size))
        }
    }

    @Test fun reedSolomonFailsHonestlyWithTooFewShards() {
        val shards = FecCodec.split(ByteArray(100) { it.toByte() }, 4, 2)
        assertNull(FecCodec.join(mapOf(0 to shards[0], 5 to shards[5], 2 to shards[2]), 4, 2, 100))
    }

    private fun features(attempt: Int = 1, consecutive: Int = 1, timeoutRate: Double = 0.1, age: Long = 500) =
        RecoveryFeatures(80.0, 20.0, timeoutRate, 0.5, consecutive, 0, 1, age, 5000, attempt, 4, 300)

    @Test fun deterministicPolicyRules() {
        val p = DeterministicRecoveryPolicy()
        assertEquals(RecoveryAction.RETRY_NOW, p.decide(features()).action)
        assertEquals(RecoveryAction.WAIT_RETRY, p.decide(features(consecutive = 2)).action)
        assertEquals(RecoveryAction.ADD_REDUNDANCY, p.decide(features(consecutive = 3, timeoutRate = 0.5)).action)
        assertEquals(RecoveryAction.MARK_STALE, p.decide(features(attempt = 3)).action)
        assertEquals(RecoveryAction.MARK_STALE, p.decide(features(age = 4500)).action)
    }

    private fun tinyModel(outputBias: DoubleArray): Mlp {
        val n = RecoveryFeatures.NAMES.size
        return Mlp(
            RecoveryFeatures.NAMES, RecoveryAction.entries.map { it.name },
            DoubleArray(n), DoubleArray(n) { 1.0 },
            listOf(Mlp.Layer(n, 4, false, DoubleArray(4 * n), outputBias)),
            ModelMetadata(mapOf("trained_at" to "test")),
        )
    }

    @Test fun mlPolicyPicksCheapestAndAbstainsWhenUnsure() {
        val confident = MlRecoveryPolicy(tinyModel(doubleArrayOf(1.0, 0.2, 2.0, 3.0)))
        val d = confident.decide(features())
        assertEquals(RecoveryAction.WAIT_RETRY, d.action)
        assertEquals("ml", d.source)
        val unsure = MlRecoveryPolicy(tinyModel(doubleArrayOf(1.0, 0.99, 2.0, 3.0)))
        val d2 = unsure.decide(features())
        assertTrue(d2.source.startsWith("ml-rejected"))
        assertEquals(DeterministicRecoveryPolicy().decide(features()).action, d2.action)
    }

    @Test fun modelFileRoundTripsAndBadFilesAreRejected() {
        val m = tinyModel(doubleArrayOf(1.0, 0.2, 2.0, 3.0))
        val ok = MlRecoveryPolicy.load(m.write().byteInputStream())
        assertTrue(ok is MlRecoveryPolicy.Companion.Load.Ready)
        assertTrue(MlRecoveryPolicy.load(null) is MlRecoveryPolicy.Companion.Load.Unavailable)
        assertTrue(MlRecoveryPolicy.load("garbage".byteInputStream()) is MlRecoveryPolicy.Companion.Load.Unavailable)
        val wrongFeatures = m.write().replace("rtt_mean_s", "something_else")
        assertTrue(MlRecoveryPolicy.load(wrongFeatures.byteInputStream()) is MlRecoveryPolicy.Companion.Load.Unavailable)
        val truncated = m.write().lines().dropLast(2).joinToString("\n")
        assertTrue(MlRecoveryPolicy.load(truncated.byteInputStream()) is MlRecoveryPolicy.Companion.Load.Unavailable)
    }

    @Test fun bundledModelLoadsIfPresent() {
        // The trained model is generated by :core:trainPolicy; this checks it is loadable when it exists.
        val l = MlRecoveryPolicy.loadBundled()
        if (l is MlRecoveryPolicy.Companion.Load.Ready) assertNotNull(l.policy.decide(features()))
    }

    @Test fun gapEstimateIsLabelledAndWithdrawnWhenTooUncertain() {
        val e = GapEstimator()
        val last = LocationFix(17.0, 78.0, 5f, 1.0f, 0f, 1000)
        val est = e.estimate(last, null, 10_000)!!
        assertTrue(est.latitude > 17.0) // moving north at 1 m/s
        assertEquals(20.0, est.radiusM, 0.01) // 5 m + 1.5 m/s * 10 s
        assertNull(e.estimate(last, null, 40_000)) // 65 m: no longer actionable
        assertEquals(LocationState.FRESH, GapEstimator.state(1000, false))
        assertEquals(LocationState.ESTIMATED, GapEstimator.state(8000, true))
        assertEquals(LocationState.STALE, GapEstimator.state(8000, false))
        assertEquals(LocationState.UNAVAILABLE, GapEstimator.state(null, false))
    }

    @Test fun distanceAndBearing() {
        assertEquals(111_195.0, GapEstimator.distanceM(0.0, 0.0, 1.0, 0.0), 50.0)
        assertEquals(90.0, GapEstimator.bearingDeg(0.0, 0.0, 0.0, 1.0), 0.01)
    }

    @Test fun keyAgreementMatchesAndDigitsAreBound() {
        val i = SessionCrypto.newKeyPair(); val r = SessionCrypto.newKeyPair()
        val ip = i.public.encoded; val rp = r.public.encoded
        val ki = SessionCrypto.deriveKeys(i, rp, 1L, "1234", ip, rp)
        val kr = SessionCrypto.deriveKeys(r, ip, 1L, "1234", ip, rp)
        assertArrayEquals(ki.initiatorToResponder, kr.initiatorToResponder)
        assertArrayEquals(SessionCrypto.confirmTag(ki, ip, rp), SessionCrypto.confirmTag(kr, ip, rp))
        val other = SessionCrypto.deriveKeys(r, ip, 1L, "9999", ip, rp)
        assertTrue(!other.initiatorToResponder.contentEquals(ki.initiatorToResponder))
    }
}
