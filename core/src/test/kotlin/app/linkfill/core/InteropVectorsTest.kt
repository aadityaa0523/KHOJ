package app.linkfill.core

import app.linkfill.core.mesh.CrewKey
import app.linkfill.core.mesh.GattFraming
import app.linkfill.core.mesh.MeshMessage
import app.linkfill.core.mesh.MeshPacket
import app.linkfill.core.mesh.MeshType
import app.linkfill.core.mesh.PublicMessage
import app.linkfill.core.mesh.SosKind
import app.linkfill.core.security.SessionCrypto
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Writes docs/interop/khoj_test_vectors.json: exact bytes another platform (an iOS app) must reproduce to join the
 * mesh. Everything is deterministic (AES-GCM nonces come from packet ids), so the file only changes when the
 * protocol does; a diff in that file is a protocol change.
 */
class InteropVectorsTest {
    private fun hex(b: ByteArray) = b.joinToString("") { "%02x".format(it) }

    @Test fun writeVectors() {
        val code = "ABCDEFGHJKLMNPQR"
        val crew = CrewKey.fromCode(code)!!
        val secret = code.map { "ABCDEFGHJKLMNPQRSTUVWXYZ23456789".indexOf(it).toByte() }.toByteArray()
        val salt = "KHOJ crew v2".toByteArray(Charsets.UTF_8)
        val contentKey = SessionCrypto.hkdf(salt, secret, "content".toByteArray(Charsets.UTF_8), 32)
        val tagKey = SessionCrypto.hkdf(salt, secret, "tag".toByteArray(Charsets.UTF_8), 32)
        val tunnelKey = SessionCrypto.hkdf(salt, secret, "tunnel".toByteArray(Charsets.UTF_8), 32)

        val origin = 0x11223344; val pid = 7; val t = 1_790_000_000L; val runEpoch = 0x55667788
        val tag = crew.tagForTime(t)
        val (type, plain) = MeshMessage.encode(MeshMessage.Beacon(25.3176, 82.9739, 12, 80, "Asha", findable = false))
        val bare = MeshPacket(type, 6, 0, origin, 1, tag, runEpoch, origin, pid, t, ByteArray(0))
        val beacon = MeshPacket(type, 6, 0, origin, 1, tag, runEpoch, origin, pid, t, crew.seal(bare, plain))
        val beaconFrame = MeshPacket.encode(beacon)
        assertTrue(plain.contentEquals(crew.open(MeshPacket.decode(beaconFrame)!!)))

        val (sosType, sosBody) = PublicMessage.encode(PublicMessage.PublicSos(SosKind.MANUAL, 25.3176, 82.9739, "Asha"))
        val sosFrame = MeshPacket.encode(MeshPacket(sosType, 6, 0, origin, 2, 0L, runEpoch, origin, pid + 1, t, sosBody))
        assertEquals(MeshType.PUBLIC_SOS, sosType)

        val frags185 = GattFraming.split(1, beaconFrame, 185)
        val frags23 = GattFraming.split(2, beaconFrame, 23)

        val json = """
            |{
            |  "_about": "KHOJ wire-format test vectors, generated by core/src/test/.../InteropVectorsTest.kt. See docs/GATT_BEARER.md.",
            |  "version": 2,
            |  "crew_code": "$code",
            |  "crew_secret_hex": "${hex(secret)}",
            |  "hkdf": { "hash": "SHA-256", "salt_utf8": "KHOJ crew v2" },
            |  "content_key_hex": "${hex(contentKey)}",
            |  "tag_key_hex": "${hex(tagKey)}",
            |  "crew_id_int32_be": ${crew.crewId},
            |  "crew_tag_uint64": ${java.lang.Long.toUnsignedString(tag)},
            |  "tunnel_key_hex": "${hex(tunnelKey)}",
            |  "beacon": {
            |    "fields": { "type": 1, "ttl": 6, "hops": 0, "relayId": $origin, "linkSeq": 1, "crewTag": ${java.lang.Long.toUnsignedString(tag)}, "runEpoch": $runEpoch, "originId": $origin, "packetId": $pid, "originTimeS": $t },
            |    "plaintext_hex": "${hex(plain)}",
            |    "aad_hex": "${hex(bare.aad())}",
            |    "nonce_hex": "${hex(java.nio.ByteBuffer.allocate(12).putInt(runEpoch).putInt(origin).putInt(pid).array())}",
            |    "gcm_tag_bytes": ${CrewKey.TAG_BYTES},
            |    "frame_hex": "${hex(beaconFrame)}"
            |  },
            |  "public_sos_frame_hex": "${hex(sosFrame)}",
            |  "gatt_fragments_mtu185_hex": [${frags185.joinToString { "\"${hex(it)}\"" }}],
            |  "gatt_fragments_mtu23_hex": [${frags23.joinToString { "\"${hex(it)}\"" }}]
            |}
            |""".trimMargin()
        val dir = File("../docs/interop").apply { mkdirs() }
        File(dir, "khoj_test_vectors.json").writeText(json)
    }
}
